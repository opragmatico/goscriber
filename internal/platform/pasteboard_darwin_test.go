// testPasteboard is a private pasteboard, so the tests never touch the
// user's clipboard.
func testPasteboard(t *testing.T) Pasteboard {
	t.Helper()
	p := Pasteboard{name: fmt.Sprintf("io.github.opragmatico.goscriber.test.%d.%s", os.Getpid(), t.Name())}
	t.Cleanup(p.release)
	return p
}

type typed struct {
	Type string
	Data []byte
}

// encodeSnapshot builds what Save produces, to restore arbitrary contents.
func encodeSnapshot(items [][]typed) []byte {
	var b bytes.Buffer
	u32 := func(n int) { _ = binary.Write(&b, binary.LittleEndian, uint32(n)) }
	u32(len(items))
	for _, item := range items {
		u32(len(item))
		for _, td := range item {
			u32(len(td.Type))
			b.WriteString(td.Type)
			u32(len(td.Data))
			b.Write(td.Data)
		}
	}
	return b.Bytes()
}

func decodeSnapshot(t *testing.T, data []byte) [][]typed {
	t.Helper()
	r := bytes.NewReader(data)
	u32 := func() int {
		var v uint32
		if err := binary.Read(r, binary.LittleEndian, &v); err != nil {
			t.Fatalf("bad snapshot: %v", err)
		}
		return int(v)
	}
	read := func(n int) []byte {
		p := make([]byte, n)
		if _, err := r.Read(p); err != nil && n > 0 {
			t.Fatalf("bad snapshot: %v", err)
		}
		return p
	}
	items := make([][]typed, u32())
	for i := range items {
		items[i] = make([]typed, u32())
		for j := range items[i] {
			items[i][j].Type = string(read(u32()))
			items[i][j].Data = read(u32())
		}
	}
	// The order of types within an item is the pasteboard's; compare sets.
	for _, item := range items {
		slices.SortFunc(item, func(a, b typed) int { return bytes.Compare([]byte(a.Type), []byte(b.Type)) })
	}
	return items
}

// contents returns everything on p.
func contents(t *testing.T, p Pasteboard) [][]typed {
	t.Helper()
	snapshot, err := p.snapshot()
	if err != nil {
		t.Fatal(err)
	}
	return decodeSnapshot(t, snapshot)
}

func TestPasteboardSetText(t *testing.T) {
	p := testPasteboard(t)
	before := p.ChangeCount()
	if err := p.SetText("Grüße, 世界 👋\x00after NUL", false); err != nil {
		t.Fatal(err)
	}
	if got, ok := p.Text(); !ok || got != "Grüße, 世界 👋" { // C strings end at the NUL on the way back
		t.Errorf("Text = %q, %v", got, ok)
	}
	if p.ChangeCount() == before {
		t.Error("the change count did not move")
	}
	items := contents(t, p)
	if len(items) != 1 || len(items[0]) != 1 || items[0][0].Type != "public.utf8-plain-text" {
		t.Errorf("contents %+v, want plain text only", items)
	}

	if err := p.SetText("Ask not.", true); err != nil {
		t.Fatal(err)
	}
	var types []string
	for _, td := range contents(t, p)[0] {
		types = append(types, td.Type)
	}
	want := []string{"org.nspasteboard.AutoGeneratedType", "org.nspasteboard.TransientType", "public.utf8-plain-text"}
	if !slices.Equal(types, want) {
		t.Errorf("transient text types %v, want %v", types, want)
	}
}

// What Save captures, the restore function puts back exactly: several
// items, several types each, binary data included.
func TestPasteboardSaveRestoresEverything(t *testing.T) {
	p := testPasteboard(t)
	original := [][]typed{
		{
			{"public.utf8-plain-text", []byte("styled text")},
			{"public.rtf", []byte(`{\rtf1\ansi {\b styled} text}`)},
			{"io.github.opragmatico.goscriber.binary", []byte{0, 1, 2, 255, 0}},
		},
		{
			{"public.png", bytes.Repeat([]byte{0x89, 'P', 'N', 'G'}, 1000)},
		},
	}
	if err := p.restore(encodeSnapshot(original)); err != nil {
		t.Fatal(err)
	}
	// macOS adds types it derives, such as UTF-16 text from UTF-8 text.
	want := contents(t, p)
	if len(want) != 2 || len(want[0]) < 3 || len(want[1]) != 1 {
		t.Fatalf("setup wrote %d items", len(want))
	}

	restore, err := p.Save()
	if err != nil {
		t.Fatal(err)
	}
	if err := p.SetText("the transcript", true); err != nil {
		t.Fatal(err)
	}
	if err := restore(); err != nil {
		t.Fatal(err)
	}
	if got := contents(t, p); !reflect.DeepEqual(got, want) {
		t.Errorf("restored %+v\nwant %+v", got, want)
	}
}

func TestPasteboardRestoresEmpty(t *testing.T) {
	p := testPasteboard(t)
	if err := p.restore(encodeSnapshot(nil)); err != nil {
		t.Fatal(err)
	}
	restore, err := p.Save()
	if err != nil {
		t.Fatal(err)
	}
	if err := p.SetText("the transcript", true); err != nil {
		t.Fatal(err)
	}
	if err := restore(); err != nil {
		t.Fatal(err)
	}
	if _, ok := p.Text(); ok || len(contents(t, p)) != 0 {
		t.Errorf("the pasteboard was empty and is not after the restore: %+v", contents(t, p))
	}
}

func TestPasteboardRejectsATruncatedSnapshot(t *testing.T) {
	p := testPasteboard(t)
	full := encodeSnapshot([][]typed{{{"public.utf8-plain-text", []byte("hello")}}})
	if err := p.restore(full[:len(full)-2]); err == nil {
		t.Error("a truncated snapshot was accepted")
	}
}

func TestUTF16Chunks(t *testing.T) {
	for _, tc := range []struct {
		text string
		n    int
		want []int // chunk lengths in UTF-16 units
	}{
		{"", 20, nil},
		{"hello", 20, []int{5}},
		{"abcdefghij", 4, []int{4, 4, 2}},
		{"abc👋def", 4, []int{3, 4, 1}}, // the emoji's two halves stay together
		{"👋👋👋", 3, []int{2, 2, 2}},
	} {
		var got []int
		var all []uint16
		for _, c := range utf16Chunks(tc.text, tc.n) {
			got = append(got, len(c))
			all = append(all, c...)
		}
		if !slices.Equal(got, tc.want) {
			t.Errorf("utf16Chunks(%q, %d) lengths %v, want %v", tc.text, tc.n, got, tc.want)
		}
		if back := string(utf16.Decode(all)); back != tc.text {
			t.Errorf("chunks of %q join to %q", tc.text, back)
		}
	}
}

// Without the Accessibility permission, which test runners lack, every key
// method refuses rather than posting events macOS would drop. With it the
// test is skipped: it would type into whatever app has focus.
func TestKeyboardWithoutPermission(t *testing.T) {
	if AccessibilityTrusted() {
		t.Skip("this process has the Accessibility permission; not posting real key presses")
	}
	k := Keyboard{}
	for name, f := range map[string]func() error{
		"Paste":       k.Paste,
		"PressReturn": k.PressReturn,
		"Type":        func() error { return k.Type("hello") },
	} {
		if err := f(); !errors.Is(err, output.ErrNoPermission) {
			t.Errorf("%s: %v, want ErrNoPermission", name, err)
		}
	}
}
