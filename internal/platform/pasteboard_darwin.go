import "C"

import (
	"errors"
	"fmt"
	"unsafe"

	"github.com/opragmatico/goscriber/internal/output"
)

// Pasteboard is a macOS pasteboard: the general one, which is the
// clipboard, or a private named one. It implements output.Clipboard.
// NSPasteboard may be used from any thread.
type Pasteboard struct{ name string }

var _ output.Clipboard = Pasteboard{}

// GeneralPasteboard is the clipboard.
func GeneralPasteboard() Pasteboard { return Pasteboard{} }

// cname returns p's name as a C string for the duration of a call, or nil
// for the general pasteboard.
func (p Pasteboard) cname() (*C.char, func()) {
	if p.name == "" {
		return nil, func() {}
	}
	s := C.CString(p.name)
	return s, func() { C.free(unsafe.Pointer(s)) }
}

// ChangeCount implements output.Clipboard.
func (p Pasteboard) ChangeCount() int {
	name, free := p.cname()
	defer free()
	return int(C.gsPasteboardChangeCount(name))
}

// Text returns the pasteboard's plain text, and false when it holds none.
func (p Pasteboard) Text() (string, bool) {
	name, free := p.cname()
	defer free()
	s := C.gsPasteboardText(name)
	if s == nil {
		return "", false
	}
	defer C.free(unsafe.Pointer(s))
	return C.GoString(s), true
}

// SetText implements output.Clipboard.
func (p Pasteboard) SetText(text string, transient bool) error {
	name, free := p.cname()
	defer free()
	ctext := C.CString(text) // NUL-terminated, but the length is passed: NULs inside survive
	defer C.free(unsafe.Pointer(ctext))
	t := C.int(0)
	if transient {
		t = 1
	}
	if C.gsPasteboardSetText(name, ctext, C.size_t(len(text)), t) != 0 {
		return errors.New("platform: could not write to the clipboard")
	}
	return nil
}

// Save implements output.Clipboard: it copies every item in every type
// into Go memory, so the snapshot survives whatever happens to the
// pasteboard, and the returned function writes it back.
func (p Pasteboard) Save() (func() error, error) {
	snapshot, err := p.snapshot()
	if err != nil {
		return nil, err
	}
	return func() error { return p.restore(snapshot) }, nil
}

// snapshot copies the pasteboard into the format restore reads.
func (p Pasteboard) snapshot() ([]byte, error) {
	name, free := p.cname()
	defer free()
	var n C.size_t
	buf := C.gsPasteboardSave(name, &n)
	if buf == nil {
		return nil, errors.New("platform: out of memory saving the clipboard")
	}
	defer C.free(buf)
	return C.GoBytes(buf, C.int(n)), nil
}

func (p Pasteboard) restore(snapshot []byte) error {
	name, free := p.cname()
	defer free()
	var data unsafe.Pointer
	if len(snapshot) > 0 {
		data = unsafe.Pointer(&snapshot[0])
	}
	if rc := C.gsPasteboardRestore(name, data, C.size_t(len(snapshot))); rc != 0 {
		return fmt.Errorf("platform: could not restore the clipboard (%d)", int(rc))
	}
	return nil
}

// release gives a private pasteboard back to the system.
func (p Pasteboard) release() {
	if p.name == "" {
		return
	}
	name, free := p.cname()
	defer free()
	C.gsPasteboardRelease(name)
}
