#!/usr/bin/env bash
# Build the pinned NeMo-Speech.cpp ASR SDK and install it into .deps/nemo-speech,
# where the CGo binding (internal/engine/nemo) finds it through pkg-config.
# `make deps` runs this script; docs/engine-sdk.md explains the choices.
#
# The pin is the commit of the third_party/nemo-speech submodule. When an SDK
# built from that commit with the same options is already installed, the
# script only refreshes the pkg-config file and exits.
#
# Usage: scripts/build-nemo-speech.sh [--force | --stamp | --help]
#
#   --force   rebuild and reinstall even when the SDK is up to date
#   --stamp   print the build stamp an installed SDK must match, and exit
#             (CI hashes it into the SDK cache key; needs no submodule checkout)
#
# Environment:
#   NEMO_SPEECH_PRESET      upstream CMake preset; default metal-asr on Apple
#                           Silicon and cpu-asr on Linux
#   NEMO_SPEECH_CMAKE_ARGS  extra CMake arguments, split on spaces, for example
#                           -DGGML_NATIVE=OFF (CI uses it for portable CPU code)
#   MACOSX_DEPLOYMENT_TARGET  oldest macOS the libraries load on (default 13.3)
#
# Written for the bash 3.2 that macOS ships.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC_REL=third_party/nemo-speech
SRC="$ROOT/$SRC_REL"
PREFIX="$ROOT/.deps/nemo-speech"
WORK="$ROOT/.deps/build"
STAMP_FILE="$PREFIX/share/goscriber/build-stamp"
PC_NAME=nemo-speech-asr
PC_FILE="$PREFIX/lib/pkgconfig/$PC_NAME.pc"
CMAKE_MIN=3.26

# Bump when the build recipe changes in a way the rest of the stamp does not
# show, so installed SDKs and CI caches are rebuilt.
RECIPE=1

# ASR only: no diarization, TTS, translation, CLI, servers, examples, tests or
# tools, and no text normalisation (Sparrowhawk/OpenFST is off upstream on
# macOS). The libraries go to lib/ on every platform, never lib64/.
COMPONENT_ARGS="-DNEMO_SPEECH_BUILD_ASR=ON
-DNEMO_SPEECH_BUILD_DIAR=OFF
-DNEMO_SPEECH_BUILD_TTS=OFF
-DNEMO_SPEECH_BUILD_NMT=OFF
-DNEMO_SPEECH_BUILD_SPEECHLM=OFF
-DNEMO_SPEECH_BUILD_S2S=OFF
-DNEMO_SPEECH_BUILD_CLI=OFF
-DNEMO_SPEECH_BUILD_MIC_CAPTURE=OFF
-DNEMO_SPEECH_BUILD_HTTP=OFF
-DNEMO_SPEECH_BUILD_GRPC=OFF
-DNEMO_SPEECH_BUILD_EXAMPLES=OFF
-DNEMO_SPEECH_BUILD_TESTS=OFF
-DNEMO_SPEECH_BUILD_TOOLS=OFF
-DNEMO_SPEECH_WITH_NORM=OFF
-DNEMO_SPEECH_WITH_FLASHLIGHT=OFF
-DCMAKE_INSTALL_LIBDIR=lib"

log() { printf '==> %s\n' "$*" >&2; }
die() { printf 'build-nemo-speech: %s\n' "$*" >&2; exit 1; }

usage() { sed -n '2,/^# Written for/{/^# Written for/d;s/^# \{0,1\}//;p;}' "${BASH_SOURCE[0]}"; }

mode=build
case "${1:-}" in
    "") ;;
    --force) mode=force ;;
    --stamp) mode=stamp ;;
    -h | --help) usage; exit 0 ;;
    *) die "unknown argument '$1' (see --help)" ;;
esac
[ $# -le 1 ] || die "too many arguments (see --help)"

# The pinned commit, read from the index so the submodule need not be
# checked out.
commit="$(git -C "$ROOT" ls-files --stage -- "$SRC_REL" | awk '$1 == "160000" { print $2 }')"
[ -n "$commit" ] || die "$SRC_REL is not a submodule in this checkout"

if [ -n "${NEMO_SPEECH_PRESET:-}" ]; then
    preset="$NEMO_SPEECH_PRESET"
else
    case "$(uname -s)/$(uname -m)" in
        Darwin/arm64) preset=metal-asr ;;
        Linux/*) preset=cpu-asr ;;
        *) die "no default preset for $(uname -s) $(uname -m); set NEMO_SPEECH_PRESET, for example to cpu-asr" ;;
    esac
fi

# CMake would target the build host's macOS version; pin the minimum that
# upstream's release archives use instead.
platform_args=
if [ "$(uname -s)" = Darwin ]; then
    platform_args="-DCMAKE_OSX_DEPLOYMENT_TARGET=${MACOSX_DEPLOYMENT_TARGET:-13.3}"
fi

# Unquoted on purpose: one argument per word, with globbing off.
set -f
# shellcheck disable=SC2206
cmake_args=($COMPONENT_ARGS $platform_args ${NEMO_SPEECH_CMAKE_ARGS:-})
set +f

stamp="$(
    printf 'recipe %s\n' "$RECIPE"
    printf 'nemo-speech %s\n' "$commit"
    printf 'platform %s %s\n' "$(uname -s)" "$(uname -m)"
    printf 'preset %s\n' "$preset"
    printf 'cmake %s\n' "${cmake_args[*]}"
)"

if [ "$mode" = stamp ]; then
    printf '%s\n' "$stamp"
    exit 0
fi

write_pc() { # write_pc PC_PATH VERSION
    mkdir -p "$(dirname "$1")"
    # libdir is also the run-time search path of what links against it, so
    # development builds run straight from the tree. Release bundles carry the
    # libraries themselves (docs/engine-sdk.md).
    cat >"$1" <<EOF
# Generated by scripts/build-nemo-speech.sh: NeMo-Speech.cpp $2 ($commit), preset $preset.
prefix=$PREFIX
libdir=\${prefix}/lib
includedir=\${prefix}/include

Name: $PC_NAME
Description: NeMo-Speech.cpp ASR C ABI (nemo_speech/asr.h)
URL: https://github.com/NVIDIA/NeMo-Speech.cpp
Version: $2
Cflags: -I\${includedir}
Libs: -L\${libdir} -Wl,-rpath,\${libdir} -lnemo_speech_asr_c
EOF
}

if [ "$mode" = build ] && [ -f "$STAMP_FILE" ] && [ -f "$PC_FILE" ] &&
    [ -f "$PREFIX/include/nemo_speech/asr.h" ] &&
    [ "$(cat "$STAMP_FILE")" = "$stamp" ]; then
    version="$(sed -n 's/^Version: *//p' "$PC_FILE")"
    # Rewrite the paths in case the checkout moved or .deps was copied here.
    write_pc "$PC_FILE" "$version"
    log "NeMo-Speech.cpp $version ($preset) is up to date in .deps/nemo-speech"
    exit 0
fi

# --- Prerequisites ---------------------------------------------------------

version_ge() { # version_ge A B: A >= B for dotted numbers
    [ "$(printf '%s\n%s\n' "$2" "$1" | sort -t. -k1,1n -k2,2n -k3,3n | head -n 1)" = "$2" ]
}

hint="install the prerequisites listed in docs/engine-sdk.md"
command -v git >/dev/null || die "git not found; $hint"
command -v cmake >/dev/null || die "cmake not found; $hint"
command -v ninja >/dev/null || die "ninja not found; $hint"
cmake_version="$(cmake --version | sed -n 's/^cmake version \([0-9][0-9.]*\).*/\1/p')"
version_ge "$cmake_version" "$CMAKE_MIN" ||
    die "CMake $CMAKE_MIN or newer is required, found $cmake_version; $hint"

# --- Sources ----------------------------------------------------------------

log "Checking out NeMo-Speech.cpp ${commit:0:12} and its llama.cpp submodule"
git -C "$ROOT" submodule update --init --depth 1 -- "$SRC_REL"
# llama.cpp (which also provides ggml) is the only nested submodule an ASR
# build needs.
git -C "$SRC" submodule update --init --depth 1 -- llama.cpp
[ "$(git -C "$SRC" rev-parse HEAD)" = "$commit" ] ||
    die "$SRC_REL is not at the pinned commit $commit"

version="$(sed -n 's/^NEMO_SPEECH_VERSION:[[:space:]]*\([^[:space:]]*\).*/\1/p' "$SRC/VERSION")"
[ -n "$version" ] || die "cannot read the version from $SRC_REL/VERSION"

# --- SentencePiece ------------------------------------------------------------

# Upstream's pinned, static SentencePiece, linked privately into
# libnemo_speech_asr (as in its release archives), so the SDK needs no
# SentencePiece or Abseil at run time.
deps_prefix="$WORK/prefix"
log "Building the static SentencePiece pinned by NeMo-Speech.cpp $version"
PREFIX="$deps_prefix/sentencepiece" \
    bash "$SRC/scripts/build_sentencepiece_static.sh" "$WORK/sentencepiece"

# --- NeMo-Speech.cpp ----------------------------------------------------------

build_dir="$WORK/nemo-speech-$preset"
log "Configuring NeMo-Speech.cpp $version with preset $preset"
# --fresh drops a cache left by earlier options; Ninja still rebuilds only
# what changed.
bash "$SRC/scripts/configure.sh" "$preset" \
    -B "$build_dir" --fresh \
    -DNEMO_SPEECH_DEPENDENCY_PREFIX="$deps_prefix" \
    "${cmake_args[@]}"

log "Building"
cmake --build "$build_dir" --parallel

# Install into a staging prefix and swap it in at the end, so a failed run
# never leaves a half-installed SDK that looks complete.
staging="$PREFIX.staging"
rm -rf "$staging"
log "Installing into .deps/nemo-speech"
cmake --install "$build_dir" --prefix "$staging"
[ -f "$staging/include/nemo_speech/asr.h" ] || die "the install has no nemo_speech/asr.h"
ls "$staging"/lib/libnemo_speech_asr_c.* >/dev/null 2>&1 ||
    die "the install has no libnemo_speech_asr_c"

write_pc "$staging/lib/pkgconfig/$PC_NAME.pc" "$version"
mkdir -p "$(dirname "$staging/${STAMP_FILE#"$PREFIX"/}")"
printf '%s\n' "$stamp" >"$staging/${STAMP_FILE#"$PREFIX"/}"

rm -rf "$PREFIX"
mv "$staging" "$PREFIX"
log "Installed NeMo-Speech.cpp $version ($preset) in .deps/nemo-speech"
